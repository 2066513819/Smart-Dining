def portion_ratio_for_meal(age_group: str, meal: str) -> float:
    """
    返回配方克数整体缩放倍率（相对初中 12-14 岁基准）。
    meal: breakfast / lunch / dinner
    """
    group = age_group
    # 兼容传入其它值：调用方会做 normalize，这里做最小保护
    if group not in ("primary", "junior_low", "junior_high", "senior"):
        group = "junior_high"
    meal_key = (meal or "").lower().strip()
    if meal_key == "breakfast":
        base = _sum_breakfast_midpoints("junior_high")
        cur = _sum_breakfast_midpoints(group)
    else:
        # 午餐/晚餐同表
        base = _sum_lunch_dinner_midpoints("junior_high")
        cur = _sum_lunch_dinner_midpoints(group)
    if base <= 0:
        return 1.0
    return round(cur / base, 4)

